# try (спробуй) — тут ми пишемо код, який потенційно може викликати помилку.
# except (виняток) — тут ми пишемо план дій, ЯКЩО помилка сталася.
# else (інакше) — виконується, якщо помилок НЕ було (рідко використовується, але корисно знати).
# finally (нарешті) — виконується ЗАВЖДИ, була помилка чи ні (ідеально для закриття файлів чи з'єднань).

import time

def safe_calculator(a, b):
    print(f"\n--- Обчислюємо: {a} / {b} ---")
    
    try:
        # 1. СПРОБА (TRY)
        # Тут код, який може "впасти".
        # Ми намагаємось перетворити вхідні дані на числа і поділити.
        
        num1 = int(a)  # Може виникнути ValueError, якщо a = "привіт"
        num2 = int(b)  # Може виникнути ValueError
        result = num1 / num2 # Може виникнути ZeroDivisionError, якщо num2 = 0
        
    except ValueError:
        # 2. ВИНЯТОК (EXCEPT) - Проблема з типом даних
        # Спрацює, якщо користувач ввів текст замість числа.
        print("🔴 Помилка: Введіть коректні числа (цифрами)!")
        
    except ZeroDivisionError:
        # 2. ВИНЯТОК (EXCEPT) - Ділення на нуль
        # Спрацює, якщо друге число = 0.
        print("🔴 Помилка: Ділити на нуль не можна!")
        
    except Exception as e:
        # 2. ВИНЯТОК (EXCEPT) - Універсальний перехоплювач
        # Спрацює на будь-яку іншу непередбачену помилку.
        print(f"🔴 Сталася невідома помилка: {e}")
        
    else:
        # 3. ІНАКШЕ (ELSE)
        # Цей блок виконується ТІЛЬКИ якщо в блоці TRY НЕ БУЛО помилок.
        print(f"🟢 Успіх! Результат: {result}")
        
    finally:
        # 4. НАРЕШТІ (FINALLY)
        # Цей блок виконується ЗАВЖДИ (була помилка чи ні).
        # Тут закривають файли, з'єднання з БД тощо.
        print("🏁 Операцію завершено.")

# Тестуємо різні ситуації:

# 1. Успішний варіант
safe_calculator("10", "2")

# 2. Помилка: Ділення на нуль
safe_calculator("5", "0")

# 3. Помилка: Некоректні дані (літери)
safe_calculator("10", "два")